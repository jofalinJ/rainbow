-- Professional Couriers: manually managed shipping, separately confirmed WhatsApp opens.
-- Historical orders/invoices/payments remain unchanged.
create table if not exists public.order_shipments (
 id uuid primary key default gen_random_uuid(),
 order_id uuid not null unique references public.orders(id) on delete cascade,
 courier_provider text not null default 'The Professional Couriers' check (courier_provider='The Professional Couriers'),
 consignment_number text,
 dispatch_date date,
 status text not null default 'packed' check (status in ('packed','shipped','in_transit','out_for_delivery','delivered','exception')),
 created_by uuid not null references auth.users(id),
 updated_by uuid not null references auth.users(id),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint shipment_awb_format check (consignment_number is null or consignment_number ~ '^[A-Za-z0-9][A-Za-z0-9/-]{5,39}$'),
 constraint shipped_requires_awb check (status='packed' or (consignment_number is not null and dispatch_date is not null))
);
create unique index if not exists uq_order_shipment_awb on public.order_shipments(consignment_number) where consignment_number is not null;
create index if not exists idx_order_shipments_updated on public.order_shipments(updated_at desc);

create table if not exists public.shipment_events (
 id bigint generated by default as identity primary key,
 shipment_id uuid not null references public.order_shipments(id) on delete cascade,
 old_values jsonb,
 new_values jsonb not null,
 actor_id uuid not null references auth.users(id),
 changed_at timestamptz not null default now()
);
create index if not exists idx_shipment_events_order on public.shipment_events(shipment_id,changed_at desc);

create table if not exists public.shipment_notifications (
 id uuid primary key default gen_random_uuid(),
 shipment_id uuid not null references public.order_shipments(id) on delete cascade,
 awb_snapshot text not null,
 channel text not null default 'whatsapp_click_to_chat' check(channel='whatsapp_click_to_chat'),
 confirmed_by uuid not null references auth.users(id),
 confirmed_at timestamptz not null default now(),
 note text not null default 'Admin manually confirmed sending in WhatsApp; delivery not verified.',
 unique(shipment_id,awb_snapshot)
);

alter table public.order_shipments enable row level security;
alter table public.shipment_events enable row level security;
alter table public.shipment_notifications enable row level security;
revoke all on public.order_shipments,public.shipment_events,public.shipment_notifications from public,anon,authenticated;
grant select on public.order_shipments,public.shipment_events,public.shipment_notifications to authenticated;

