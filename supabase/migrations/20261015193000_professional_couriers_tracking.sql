create or replace function public.audit_order_shipment()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public as $$
begin
 insert into public.shipment_events(shipment_id,old_values,new_values,actor_id)
 values(new.id,
   case when tg_op='INSERT' then null else
     jsonb_build_object('consignment_number',old.consignment_number,'dispatch_date',old.dispatch_date,'status',old.status) end,
   jsonb_build_object('consignment_number',new.consignment_number,'dispatch_date',new.dispatch_date,'status',new.status),
   new.updated_by);
 return new;
end; $$;
drop trigger if exists trg_audit_order_shipment on public.order_shipments;
create trigger trg_audit_order_shipment after insert or update
on public.order_shipments for each row execute function public.audit_order_shipment();

create or replace function public.save_order_shipment(
 p_order_id uuid, p_awb text, p_dispatch_date date, p_status text
) returns public.order_shipments language plpgsql security definer
set search_path = pg_catalog, public as $$
declare
 v_actor uuid := auth.uid();
 v_order public.orders%rowtype;
 v_result public.order_shipments%rowtype;
 v_awb text := nullif(upper(trim(coalesce(p_awb,''))),'');
begin
 if v_actor is null or not exists (
   select 1 from public.staff_profiles sp
   where sp.user_id=v_actor and sp.active and sp.role='admin'
 ) then raise exception 'Admin permission required' using errcode='42501'; end if;
 if p_order_id is null then raise exception 'Missing order ID'; end if;
 select * into v_order from public.orders where id=p_order_id for update;
 if not found then raise exception 'Order not found'; end if;
 if v_order.source::text <> 'online' then raise exception 'Only online customer shipments can be managed here'; end if;
 if v_order.payment_status::text <> 'paid' then raise exception 'Verify payment before dispatching'; end if;
 if v_order.status::text in ('cancelled','refunded') then raise exception 'Cancelled or refunded orders cannot be shipped'; end if;
 if p_status is null or p_status not in ('packed','shipped','in_transit','out_for_delivery','delivered','exception') then
   raise exception 'Invalid shipment status';
 end if;
 if v_awb is not null and v_awb !~ '^[A-Z0-9][A-Z0-9/-]{5,39}$' then
   raise exception 'Consignment number must be 6–40 letters, digits, / or -';
 end if;
 if p_status <> 'packed' and (v_awb is null or p_dispatch_date is null) then
   raise exception 'Add consignment number and dispatch date before marking shipped';
 end if;
 if p_dispatch_date is not null and (p_dispatch_date > (now() at time zone 'Asia/Kolkata')::date + 1 or p_dispatch_date < v_order.created_at::date - 30) then
   raise exception 'Dispatch date is outside the permitted range';
 end if;
 insert into public.order_shipments(order_id,consignment_number,dispatch_date,status,created_by,updated_by)
 values(p_order_id,v_awb,p_dispatch_date,p_status,v_actor,v_actor)
 on conflict(order_id) do update set
   consignment_number=excluded.consignment_number,
   dispatch_date=excluded.dispatch_date,
   status=excluded.status,
   updated_by=v_actor,
   updated_at=now()
 returning * into v_result;
 if p_status='packed' and v_order.status::text in ('pending','confirmed') then
   update public.orders set status='processing',updated_at=now() where id=p_order_id;
 elsif p_status in ('shipped','in_transit','out_for_delivery','exception') and v_order.status::text <> 'delivered' then
   update public.orders set status='shipped',updated_at=now() where id=p_order_id;
 elsif p_status='delivered' then
   update public.orders set status='delivered',updated_at=now() where id=p_order_id;
 end if;
 return v_result;
end; $$;

create or replace function public.confirm_shipment_whatsapp(
 p_order_id uuid, p_awb text
) returns jsonb language plpgsql security definer
set search_path = pg_catalog, public as $$
declare
 v_actor uuid:=auth.uid();
 v_ship public.order_shipments%rowtype;
 v_new_id uuid;
begin
 if v_actor is null or not exists(
   select 1 from public.staff_profiles sp where sp.user_id=v_actor and sp.active and sp.role='admin'
 ) then raise exception 'Admin permission required' using errcode='42501'; end if;
 select * into v_ship from public.order_shipments where order_id=p_order_id for update;
 if not found then raise exception 'No shipment was saved for this order'; end if;
 if v_ship.status not in ('shipped','in_transit','out_for_delivery','delivered') or v_ship.consignment_number is null then
   raise exception 'Shipment must be dispatched before confirming a tracking message';
 end if;
 if v_ship.consignment_number is distinct from upper(trim(coalesce(p_awb,''))) then
   raise exception 'Shipment details changed. Refresh before confirming.';
 end if;
 insert into public.shipment_notifications(shipment_id,awb_snapshot,confirmed_by)
 values(v_ship.id,v_ship.consignment_number,v_actor)
 on conflict(shipment_id,awb_snapshot) do nothing
 returning id into v_new_id;
 return jsonb_build_object('recorded',v_new_id is not null,'already_confirmed',v_new_id is null);
end; $$;

-- Signed-in customers see only shipments attached to their verified account email.
-- Existing tracking functions remain untouched.
create or replace function public.track_my_order_shipments()
returns table(
 order_number text,product_names text,order_status text,payment_status text,
 total_amount numeric,created_at timestamptz,courier_provider text,
 consignment_number text,dispatch_date date,shipment_status text,shipment_updated_at timestamptz
) language sql stable security definer set search_path = pg_catalog, public as $$
  select o.order_number,
     (select string_agg(distinct oi.product_name,', ' order by oi.product_name)
      from public.order_items oi where oi.order_id=o.id),
     o.status::text,o.payment_status::text,o.total_amount,o.created_at,
     s.courier_provider,s.consignment_number,s.dispatch_date,s.status,s.updated_at
  from public.orders o
  join public.customers c on c.id=o.customer_id
  left join public.order_shipments s on s.order_id=o.id
  where auth.uid() is not null
    and nullif(trim(coalesce(auth.jwt()->>'email','')),'') is not null
    and lower(trim(coalesce(c.email,'')))=lower(trim(auth.jwt()->>'email'))
    and o.source::text='online'
  order by o.created_at desc limit 30;
$$;

-- Public guest lookup requires both an item code and the full matching phone number,
-- as the existing lookup does. It returns no phone, name or delivery address.
create or replace function public.track_guest_order_shipments(
 p_product_code text,p_phone text
) returns table(order_number text,product_name text,order_status text,payment_status text,
 created_at timestamptz,courier_provider text,consignment_number text,
 dispatch_date date,shipment_status text,shipment_updated_at timestamptz)
language sql stable security definer set search_path = pg_catalog, public as $$
 select distinct o.order_number,oi.product_name,o.status::text,o.payment_status::text,
    o.created_at,s.courier_provider,s.consignment_number,s.dispatch_date,s.status,s.updated_at
 from public.orders o
 join public.customers c on c.id=o.customer_id
 join public.order_items oi on oi.order_id=o.id
 left join public.order_shipments s on s.order_id=o.id
 where o.source::text='online'
 and length(trim(coalesce(p_product_code,''))) between 1 and 64
 and length(regexp_replace(coalesce(p_phone,''),'[^0-9]','','g')) between 10 and 12
 and upper(trim(oi.product_code))=upper(trim(p_product_code))
 and right(regexp_replace(c.whatsapp_number,'[^0-9]','','g'),10)
 = right(regexp_replace(p_phone,'[^0-9]','','g'),10)
 order by o.created_at desc limit 10;
$$;

